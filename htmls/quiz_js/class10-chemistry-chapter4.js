// Render quiz based on selected level
function renderQuiz(level) {
    const quizContainer = document.getElementById("quizContainer");
    if (!quizContainer) return;

    quizContainer.innerHTML = ""; // Clear previous questions

    if (!quizData[level]) {
        quizContainer.innerHTML = '<div class="alert alert-danger">Error loading quiz data.</div>';
        return;
    }

    quizData[level].forEach((item, index) => {
        const card = document.createElement("div");
        card.className = "card animate__animated animate__fadeInUp";
        card.style.marginBottom = "20px";
        card.innerHTML = `
      <div class="card__content" style="padding: 20px;">
        <h5 style="margin-bottom: 15px; color: #ffffff;">Q${index + 1}: ${item.question}</h5>
        <div class="options-container">
          ${item.options.map(option => `
            <label style="display: block; margin: 10px 0; cursor: pointer; color: #b0b3b8;">
              <input type="radio" name="q${index}" value="${option.replace(/"/g, '&quot;')}" style="margin-right: 10px;"> 
              <span>${option}</span>
            </label>
          `).join("")}
        </div>
      </div>
    `;
        quizContainer.appendChild(card);
    });
}

// Check answers and display score
function checkAnswers(level) {
    let score = 0;
    const totalQuestions = quizData[level].length;
    const resultDiv = document.getElementById("result");

    quizData[level].forEach((item, index) => {
        const selected = document.querySelector(`input[name="q${index}"]:checked`);
        if (selected) {
            const userAnswer = selected.value;
            if (userAnswer === item.answer) {
                score++;
                selected.parentElement.style.color = "#00b894";
                selected.parentElement.style.fontWeight = "bold";
            } else {
                selected.parentElement.style.color = "#ff7675";
                // Show correct answer for wrong answers
                const optionsContainer = selected.parentElement.parentElement;
                const correctLabel = Array.from(optionsContainer.querySelectorAll('label')).find(
                    label => label.textContent.trim() === item.answer
                );
                if (correctLabel) {
                    correctLabel.style.color = "#00b894";
                    correctLabel.style.fontWeight = "bold";
                }
            }
        }
    });

    const percentage = Math.round((score / totalQuestions) * 100);
    let feedback = "";
    if (score === totalQuestions) {
        feedback = "🎉 Perfect score! You're a Carbon Chemistry expert! Ready for board exams! 😎";
    } else if (score >= totalQuestions * 0.7) {
        feedback = "👍 Good job! Review the incorrect answers to master homologous series and functional groups! 🚀";
    } else if (score >= totalQuestions * 0.4) {
        feedback = "📚 Keep practicing! Focus on covalent bonding, homologous series, and chemical properties! 💪";
    } else {
        feedback = "📖 Need more practice! Re-read NCERT Chapter 4 and practice PYQs again! 🌟";
    }

    if (resultDiv) {
        resultDiv.innerHTML = `
      <div class="result-card" style="background: #1a1d26; padding: 20px; border-radius: 10px; margin-top: 20px; text-align: center;">
        <h3 style="color: #6c5ce7;">Your Score: ${score}/${totalQuestions}</h3>
        <p style="color: #e4e6eb;">Percentage: ${percentage}%</p>
        <p style="color: #b0b3b8;">${feedback}</p>
        <p class="text-muted mt-2"><small>✨ Includes Previous Year Questions from CBSE Board Exams 2019-2024 ✨</small></p>
        <button class="btn btn-primary mt-3" onclick="location.reload()" style="background: #6c5ce7; border: none;">Try Again 🔄</button>
      </div>
    `;
        resultDiv.className = "result animate__animated animate__bounceIn";
        resultDiv.style.display = "block";
    }
}

// Initialize quiz when DOM is loaded
document.addEventListener("DOMContentLoaded", () => {
    // Wait for DOM to be fully loaded
    setTimeout(() => {
        renderQuiz("level1");
    }, 100);

    const levelSelect = document.getElementById("levelSelect");
    const submitBtn = document.getElementById("submitQuiz");

    if (levelSelect) {
        levelSelect.addEventListener("change", function () {
            const selectedLevel = this.value;
            renderQuiz(selectedLevel);
            if (submitBtn) {
                submitBtn.onclick = () => checkAnswers(selectedLevel);
            }
        });
    }

    if (submitBtn) {
        submitBtn.onclick = () => {
            const selectedLevel = levelSelect ? levelSelect.value : "level1";
            checkAnswers(selectedLevel);
        };
    }
});

