const allowedOrigins = [
    'https://neobranium.web.app',
    'http://localhost:5500',
    'http://localhost:5501',
    'http://127.0.0.1:5500',
    'http://127.0.0.1:5501',
    ...((process.env.ALLOWED_ORIGINS || '').split(',').map(o => o.trim()).filter(Boolean))
];

app.use(cors({
    origin: function (origin, callback) {
        // Allow requests with no origin (like mobile apps or curl requests if explicitly permitted later)
        if (!origin) return callback(null, true);

        const isAllowed = allowedOrigins.some(allowed => origin.startsWith(allowed));
        if (isAllowed) {
            return callback(null, true);
        }

        return callback(new Error('CORS Error: Origin not allowed'), false);
    },
    credentials: true // IMPORTANT: Needed to send cookies generated by express-session!
}));

// Strict server-side origin check middleware
const strictOriginCheck = (req, res, next) => {
    // Only apply strict checks to /api routes
    if (!req.path.startsWith('/api/')) return next();

    const origin = req.headers.origin || req.headers.referer;

    // Reject requests with absolutely no origin/referer
    if (!origin) {
        console.warn(`🚨 Blocked direct API call (No Origin): ${req.ip}`);
        return res.status(403).json({ reply: 'Forbidden: Direct API access is not allowed' });
    }

    const isAllowed = allowedOrigins.some(allowedOrigin => origin.startsWith(allowedOrigin));

    if (!isAllowed) {
        console.warn(`🚨 Blocked API call from unauthorized origin: ${origin} (IP: ${req.ip})`);
        return res.status(403).json({ reply: 'Forbidden: Invalid Origin' });
    }

    next();
};

app.use(strictOriginCheck);

app.use(express.json({ limit: '2mb' }));

